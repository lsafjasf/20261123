import { mkdir, open, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { parseCueSheet } from "./cue.ts";
import { readWavInfo } from "./wav.ts";
import { buildPlan } from "./planner.ts";
import { copyRange, hashDataRange } from "./writer.ts";
import type { Manifest, OutputRecord, PlannedRegion, WavInfo } from "./types.ts";
import { fail } from "./errors.ts";

export interface SplitOptions {
  cuePath: string;
  outDir: string;
  offsetSamples: number;
  force: boolean;
}

export async function splitImage(options: SplitOptions): Promise<Manifest> {
  const cueContent = await readFile(options.cuePath, "utf8");
  const cue = parseCueSheet(cueContent, options.cuePath);
  const wavPath = path.resolve(path.dirname(options.cuePath), cue.filePath);
  const wav = await readWavInfo(wavPath);
  const plan = buildPlan(cue, wav, options.offsetSamples);

  await mkdir(options.outDir, { recursive: true });
  const sourceHandle = await open(wavPath, "r");
  const outputs: OutputRecord[] = [];
  const reconstruction = createHash("sha256");
  try {
    for (const region of plan.regions) {
      const fileName = outputFileName(region);
      const targetPath = path.join(options.outDir, fileName);
      const target = await open(targetPath, options.force ? "w" : "wx");
      try {
        const copied = await copyRange(sourceHandle, target, wav, region.startSample, region.frameCount, reconstruction);
        outputs.push(toRecord(region, fileName, copied.byteLength, copied.sha256));
      } finally {
        await target.close();
      }
    }
  } finally {
    await sourceHandle.close();
  }

  const dataSha256 = await hashDataRange(wavPath, wav.dataOffset, wav.dataBytes);
  const reconstructedHash = reconstruction.digest("hex");
  const manifest: Manifest = {
    manifestVersion: 1,
    createdAt: new Date().toISOString(),
    cueSheet: path.resolve(options.cuePath),
    source: {
      file: wavPath,
      sampleRate: wav.sampleRate,
      channels: wav.channels,
      bitsPerSample: wav.bitsPerSample,
      frameBytes: wav.frameBytes,
      totalSamples: wav.frameCount,
      dataSha256,
    },
    offset: {
      samples: options.offsetSamples,
      msfFrames: offsetToMsfFrames(options.offsetSamples, wav.sampleRate),
    },
    outputs,
    reconstructed: {
      dataBytes: outputs.reduce((sum, record) => sum + record.byteLength, 0),
      sha256: reconstructedHash,
    },
    warnings: cue.warnings,
  };

  if (manifest.reconstructed.dataBytes !== wav.dataBytes) {
    fail("LENGTH_INSUFFICIENT", `output bytes ${manifest.reconstructed.dataBytes} != source data bytes ${wav.dataBytes}.`);
  }
  if (manifest.reconstructed.sha256 !== dataSha256) {
    fail("LENGTH_INSUFFICIENT", "combined output hash differs from source hash; split is not byte-exact.");
  }

  await writeFile(path.join(options.outDir, "cdcue-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(path.join(options.outDir, "split.cue"), buildSplitCue(cue, wav, plan.regions, options.offsetSamples));
  return manifest;
}

function outputFileName(region: PlannedRegion): string {
  if (region.kind === "hidden") {
    return "00-hidden-leadin.wav";
  }
  return `${String(region.trackNumber).padStart(2, "0")}.wav`;
}

function toRecord(region: PlannedRegion, file: string, byteLength: number, sha256: string): OutputRecord {
  return {
    id: region.id,
    kind: region.kind,
    trackNumber: region.kind === "track" ? (region.trackNumber ?? null) : null,
    file,
    startSample: region.startSample,
    frameCount: region.frameCount,
    byteLength,
    sha256,
    markers: region.markers,
  };
}
function offsetToMsfFrames(offsetSamples: number, sampleRate: number): number | null {
  const numerator = offsetSamples * 75;
  if (numerator % sampleRate !== 0) {
    return null;
  }
  return numerator / sampleRate;
}

function buildSplitCue(
  cue: ReturnType<typeof parseCueSheet>,
  wav: WavInfo,
  regions: PlannedRegion[],
  offsetSamples: number,
): string {
  const lines: string[] = [
    `REM Generated by cdcue; offset=${offsetSamples} samples; marker positions below are original MSF minus offset.`,
  ];
  for (const region of regions) {
    const fileName = outputFileName(region);
    lines.push(`FILE "${fileName}" WAVE`);
    if (region.kind === "hidden") {
      lines.push("  TRACK 00 AUDIO");
      lines.push("    INDEX 01 00:00:00");
      continue;
    }
    lines.push(`  TRACK ${String(region.trackNumber).padStart(2, "0")} AUDIO`);
    for (const marker of region.markers) {
      if (marker.kind !== "index") {
        continue;
      }
      const relativeSample = marker.sample - region.startSample;
      if (relativeSample < 0 || relativeSample > region.frameCount) {
        fail("OFFSET_INVALID", `index for TRACK ${region.trackNumber} falls outside its output after offset correction.`);
      }
      const frame = Math.round((relativeSample * 75) / wav.sampleRate);
      lines.push(`    INDEX ${String(marker.indexNumber).padStart(2, "0")} ${toMsf(frame)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

function toMsf(frame: number): string {
  const minutes = Math.floor(frame / (75 * 60));
  const seconds = Math.floor((frame % (75 * 60)) / 75);
  const frames = frame % 75;
  const pad = (value: number): string => String(value).padStart(2, "0");
  return `${pad(minutes)}:${pad(seconds)}:${pad(frames)}`;
}
